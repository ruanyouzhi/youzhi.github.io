export function hexagramFromLines(lines) {
  if (lines.length !== 6) throw new Error('需要六爻才能成卦');
  const bits = lines.map((line) => String(line % 2)).join('');
  const lower = trigrams.findIndex((item) => item.bits === bits.slice(0, 3));
  const upper = trigrams.findIndex((item) => item.bits === bits.slice(3, 6));
  const number = kingWen[lower][upper];
  const [name, theme, reading, action] = meanings[number - 1];
  return { number, name, theme, reading, action, lower: trigrams[lower], upper: trigrams[upper], symbol: String.fromCodePoint(0x4dc0 + number - 1) };
}

export function transformedLines(lines) {
  return lines.map((line) => (line === 6 ? 7 : line === 9 ? 8 : line));
}

export function mbtiReading(type, hex) {
  const energy = type[0] === 'E'
    ? '你可能习惯在交流中厘清想法；先找一位愿意坦诚回应的人聊聊。'
    : '你可能习惯独自整理想法；先留一段安静时间写下自己的判断。';
  const information = type[1] === 'N'
    ? '你容易看到新的可能，也请核对眼前一项具体事实。'
    : '你擅长留意现实细节，也可以问问自己是否还有另一种可能。';
  const decision = type[2] === 'F'
    ? '做决定时，照顾相关人的感受，也别忽略自己的边界。'
    : '做决定时，列清标准和代价，也听听关系中的真实感受。';
  const pace = type[3] === 'J'
    ? '你可能偏好明确计划；给变化留一个小小的调整空间。'
    : '你可能偏好保持选择；为下一步设一个具体时间。';
  const firstStep = type[0] === 'E' ? '一次坦诚的对话' : '几行写给自己的笔记';
  return { energy, information, decision, pace, close: `面对「${hex.theme}」，先从${firstStep}开始，再选一个能在本周验证的小行动。` };
}

